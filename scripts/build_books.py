"""Rebuild the books: wiki/books/<rep>.md + .json + .calendar.json for every rep and the team files.

Books are generated views (gitignored) per PLAN.md §11. Each rep book shows:
- active accounts vs max_active, tier mix
- meetings this month (log/touches.csv status meeting_booked / meeting_held,
  distinct accounts) vs targets.meetings_per_month
- replies vs sent in the last 7 days
- today: due and overdue actions (sorted by tier, then due date) with nba /
  nba_reason; hot accounts; at-risk accounts; VAM pre-drafts waiting
- pipeline counts by stage; handed over this month

The team book has a per-rep table plus the pool (unowned accounts) by tier,
the review-queue size and the funnel.

The .md files are the agents' working view (mama-book, Codex). The .json files
carry the same numbers as data for the console's A2UI surfaces (ADR-0009). The
.calendar.json files hold every dated item for today −14…+60 days: appointments,
follow-ups due, renewals, claim lapses, events, holidays and send windows (ADR-0010).

Missing fields are tolerated everywhere. Env MAMA_TODAY=YYYY-MM-DD fixes
"today" for tests.

    python3 scripts/build_books.py              # all books
    python3 scripts/build_books.py --rep mei    # one rep book (plus team)
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mama_common import (  # noqa: E402
    STAGES, TIERS, has_vam_predraft, is_active, is_hot, iter_pages, load_reps, load_touches,
    norm, now_stamp, read_csv, repo_root, risk_flags, setup_stdout, stage_rank, tier_rank,
    to_date, today, write_text,
)

MEETING_STATUSES = {"meeting_booked", "meeting_held"}
FAR = dt.date(9999, 12, 31)


def _int(v, default: int | None = None) -> int | None:
    try:
        return int(v)
    except (TypeError, ValueError):
        return default


def _target(rep: dict) -> int | None:
    t = rep.get("targets")
    return _int(t.get("meetings_per_month")) if isinstance(t, dict) else None


def _c(v) -> str:
    s = norm(v)
    return s.replace("|", "/").replace("\n", " ") if s else "-"


def rep_stats(rep: dict, accounts: list, touches: list[dict], on: dt.date) -> dict:
    """Numbers for one rep. `accounts` are Page objects owned by the rep."""
    keys = {norm(rep.get("id")).lower(), norm(rep.get("email")).lower()} - {""}
    mine_t = [t for t in touches if norm(t.get("rep")).lower() in keys]
    week_start = on - dt.timedelta(days=6)
    month_start = on.replace(day=1)

    def in_range(t, start):
        d = to_date(t.get("ts"))
        return d is not None and start <= d <= on

    meetings = {norm(t.get("account")) or f"row{i}" for i, t in enumerate(mine_t)
                if norm(t.get("status")) in MEETING_STATUSES and in_range(t, month_start)}
    sent_7 = sum(1 for t in mine_t if norm(t.get("status")) == "sent" and in_range(t, week_start))
    replies_7 = sum(1 for t in mine_t if norm(t.get("status")) == "replied" and in_range(t, week_start))
    meetings_7 = sum(1 for t in mine_t
                     if norm(t.get("status")) in MEETING_STATUSES and in_range(t, week_start))

    active = [p for p in accounts if is_active(p.meta)]
    tiers = Counter(norm(p.meta.get("tier")).upper() or "-" for p in active)
    stages = Counter(norm(p.meta.get("stage")) or "(none)" for p in accounts)
    due = sorted(
        [p for p in active if (to_date(p.meta.get("next_action_due")) or FAR) <= on],
        key=lambda p: (tier_rank(p.meta), to_date(p.meta.get("next_action_due")) or FAR, p.id))
    hot = sorted([p for p in active if is_hot(p.meta, on)], key=lambda p: (tier_rank(p.meta), p.id))
    at_risk = sorted([p for p in active if risk_flags(p.meta)], key=lambda p: (tier_rank(p.meta), p.id))
    vam = sorted([p for p in active if has_vam_predraft(p.body)], key=lambda p: (tier_rank(p.meta), p.id))
    handed = [p for p in accounts if norm(p.meta.get("stage")) == "handed_over"
              and (to_date(p.meta.get("updated")) or dt.date.min) >= month_start]
    return {
        "active": len(active), "capacity": _int(rep.get("max_active")),
        "quota": _int(rep.get("daily_quota")), "tiers": tiers, "stages": stages,
        "meetings": len(meetings), "target": _target(rep),
        "sent_7": sent_7, "replies_7": replies_7, "meetings_7": meetings_7,
        "touches_7": sum(1 for t in mine_t if in_range(t, week_start)),
        "due": due, "hot": hot, "at_risk": at_risk, "vam": vam, "handed": handed,
    }


def render_rep(rep: dict, s: dict, on: dt.date) -> str:
    rid = norm(rep.get("id"))
    cap = s["capacity"]
    tier_mix = " · ".join(f"{t} {s['tiers'].get(t, 0)}" for t in TIERS)
    if s["tiers"].get("-"):
        tier_mix += f" · untiered {s['tiers']['-']}"
    tgt = s["target"]
    out = [
        f"# Book — {norm(rep.get('name')) or rid}",
        "",
        f"_Generated by `scripts/build_books.py` for {on.isoformat()} at {now_stamp()}. "
        "Do not edit._",
        "",
        f"- Rep: `{rid}` · role {norm(rep.get('role')) or 'rep'} · markets "
        f"{', '.join(str(m) for m in (rep.get('markets') or [])) or '-'}",
        f"- Active accounts: **{s['active']} / {cap if cap is not None else '-'}**"
        + (f" ({max(cap - s['active'], 0)} slots free)" if cap is not None else ""),
        f"- Tier mix (active): {tier_mix}",
        f"- Meetings this month: **{s['meetings']} / {tgt if tgt is not None else '-'}**",
        f"- Last 7 days: **{s['replies_7']} replies / {s['sent_7']} sent** · "
        f"{s['meetings_7']} meeting touches",
        f"- Daily quota: {s['quota'] if s['quota'] is not None else '-'}",
        f"- Handed over this month: {len(s['handed'])}",
        "",
        f"## Today — due actions ({len(s['due'])})",
        "",
    ]
    if s["due"]:
        out += ["| Account | Tier | Due | Next action | NBA | Why |", "|---|---|---|---|---|---|"]
        for p in s["due"]:
            m = p.meta
            d = to_date(m.get("next_action_due"))
            due = _c(m.get("next_action_due")) + (" (overdue)" if d and d < on else "")
            out.append(f"| [[accounts/{p.id}]] {_c(m.get('name'))} | {_c(m.get('tier'))} | {due} | "
                       f"{_c(m.get('next_action'))} | {_c(m.get('nba'))} | {_c(m.get('nba_reason'))} |")
    else:
        out.append("_Nothing due._")

    def lst(title, pages, extra):
        block = ["", f"## {title} ({len(pages)})", ""]
        block += [f"- [[accounts/{p.id}]] {_c(p.meta.get('name'))} · tier {_c(p.meta.get('tier'))}"
                  f" · {extra(p)}" for p in pages] or ["_None._"]
        return block

    out += lst("Hot", s["hot"], lambda p: f"score {_c(p.meta.get('score'))} "
               f"(updated {_c(p.meta.get('score_updated'))})")
    out += lst("At risk", s["at_risk"], lambda p: ", ".join(risk_flags(p.meta)))
    out += lst("VAM pre-drafts waiting", s["vam"], lambda p: f"nba {_c(p.meta.get('nba'))}")
    out += ["", "## Pipeline by stage", "", "| Stage | Count |", "|---|---|"]
    keys = sorted(s["stages"], key=lambda k: (stage_rank(k), k))
    out += [f"| {k} | {s['stages'][k]} |" for k in keys] or ["| - | 0 |"]
    out.append("")
    return "\n".join(out)


def render_team(reps: list[dict], stats: dict[str, dict], accounts: list, root: Path,
                on: dt.date) -> str:
    pool = [p for p in accounts if not norm(p.meta.get("owner")) and is_active(p.meta)]
    pool_t = Counter(norm(p.meta.get("tier")).upper() or "-" for p in pool)
    review = [r for r in read_csv(root / "log" / "review.csv") if not norm(r.get("decision"))]
    funnel = Counter(norm(p.meta.get("stage")) or "(none)" for p in accounts)
    out = [
        "# Team book",
        "",
        f"_Generated by `scripts/build_books.py` for {on.isoformat()} at {now_stamp()}. "
        "Do not edit._",
        "",
        "## Reps",
        "",
        "| Rep | Role | Markets | Active / cap | A | B | C | Sent 7d | Replies 7d | "
        "Meetings (month) / target | Due | At risk |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for rep in reps:
        s = stats[rep["id"]]
        cap = s["capacity"] if s["capacity"] is not None else "-"
        tgt = s["target"] if s["target"] is not None else "-"
        out.append(
            f"| [{rep['id']}]({rep['id']}.md) | {_c(rep.get('role'))} | "
            f"{', '.join(str(m) for m in (rep.get('markets') or [])) or '-'} | {s['active']} / {cap} | "
            f"{s['tiers'].get('A', 0)} | {s['tiers'].get('B', 0)} | {s['tiers'].get('C', 0)} | "
            f"{s['sent_7']} | {s['replies_7']} | {s['meetings']} / {tgt} | {len(s['due'])} | "
            f"{len(s['at_risk'])} |")
    if not reps:
        out.append("| _no reps yet_ | | | | | | | | | | | |")
    out += [
        "",
        f"## Pool (unowned, active): {len(pool)}",
        "",
        " · ".join(f"{t} {pool_t.get(t, 0)}" for t in TIERS)
        + (f" · untiered {pool_t['-']}" if pool_t.get("-") else ""),
        "",
    ]
    for p in sorted(pool, key=lambda p: (tier_rank(p.meta), p.id))[:20]:
        out.append(f"- [[accounts/{p.id}]] {_c(p.meta.get('name'))} · {_c(p.meta.get('market'))} · "
                   f"tier {_c(p.meta.get('tier'))} · score {_c(p.meta.get('score'))}")
    out += ["", f"## Review queue: {len(review)} undecided", "", "## Funnel", "",
            "| Stage | Count |", "|---|---|"]
    keys = sorted(funnel, key=lambda k: (stage_rank(k), k))
    out += [f"| {k} | {funnel[k]} |" for k in keys] or ["| - | 0 |"]
    out.append("")
    return "\n".join(out)


def _acc(p, on: dt.date, **extra) -> dict:
    m = p.meta
    return {"account": p.id, "name": norm(m.get("name")), "market": norm(m.get("market")),
            "tier": norm(m.get("tier")), "stage": norm(m.get("stage")), "score": m.get("score"), **extra}


def rep_data(rep: dict, s: dict, on: dt.date) -> dict:
    """The rep book as data (same numbers as render_rep)."""
    def due_row(p):
        d = to_date(p.meta.get("next_action_due"))
        return _acc(p, on, due=norm(p.meta.get("next_action_due")), overdue=bool(d and d < on),
                    next_action=norm(p.meta.get("next_action")), nba=norm(p.meta.get("nba")),
                    nba_reason=norm(p.meta.get("nba_reason")))
    return {
        "type": "book", "rep": norm(rep.get("id")), "name": norm(rep.get("name")),
        "role": norm(rep.get("role")) or "rep", "markets": [str(m) for m in (rep.get("markets") or [])],
        "date": on.isoformat(), "generated": now_stamp(),
        "active": s["active"], "capacity": s["capacity"], "quota": s["quota"],
        "tiers": {t: s["tiers"].get(t, 0) for t in TIERS} | ({"untiered": s["tiers"]["-"]} if s["tiers"].get("-") else {}),
        "meetings": s["meetings"], "target": s["target"],
        "sent_7": s["sent_7"], "replies_7": s["replies_7"], "meetings_7": s["meetings_7"], "touches_7": s["touches_7"],
        "handed_over_month": len(s["handed"]),
        "due": [due_row(p) for p in s["due"]],
        "hot": [_acc(p, on, score_updated=norm(p.meta.get("score_updated"))) for p in s["hot"]],
        "at_risk": [_acc(p, on, flags=risk_flags(p.meta)) for p in s["at_risk"]],
        "vam_predrafts": [_acc(p, on, nba=norm(p.meta.get("nba"))) for p in s["vam"]],
        "stages": {k: s["stages"][k] for k in sorted(s["stages"], key=lambda k: (stage_rank(k), k))},
    }


def team_data(reps: list[dict], stats: dict[str, dict], accounts: list, root: Path, on: dt.date) -> dict:
    """The team book as data (same numbers as render_team)."""
    pool = [p for p in accounts if not norm(p.meta.get("owner")) and is_active(p.meta)]
    pool_t = Counter(norm(p.meta.get("tier")).upper() or "-" for p in pool)
    review = [r for r in read_csv(root / "log" / "review.csv") if not norm(r.get("decision"))]
    funnel = Counter(norm(p.meta.get("stage")) or "(none)" for p in accounts)
    rows = []
    for rep in reps:
        s = stats[rep["id"]]
        rows.append({"rep": rep["id"], "name": norm(rep.get("name")), "role": norm(rep.get("role")) or "rep",
                     "markets": [str(m) for m in (rep.get("markets") or [])], "active": s["active"],
                     "capacity": s["capacity"], "tiers": {t: s["tiers"].get(t, 0) for t in TIERS},
                     "sent_7": s["sent_7"], "replies_7": s["replies_7"], "meetings": s["meetings"],
                     "target": s["target"], "due": len(s["due"]), "at_risk": len(s["at_risk"]),
                     "quota": s["quota"]})
    return {
        "type": "team_book", "date": on.isoformat(), "generated": now_stamp(), "reps": rows,
        "pool": {"count": len(pool), "tiers": {t: pool_t.get(t, 0) for t in TIERS}
                 | ({"untiered": pool_t["-"]} if pool_t.get("-") else {}),
                 "top": [_acc(p, on) for p in sorted(pool, key=lambda p: (tier_rank(p.meta), p.id))[:20]]},
        "review_open": len(review),
        "funnel": {k: funnel[k] for k in sorted(funnel, key=lambda k: (stage_rank(k), k))},
    }


def _write_json(path: Path, data: dict) -> None:
    write_text(path, json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n")


# ----------------------------------------------------------------------------
# Calendar (ADR-0010, spec §6.1–6.2): everything with a date, as data for the console
# ----------------------------------------------------------------------------
CAL_BEFORE, CAL_AFTER = 14, 60      # window: today −14 … +60 days
RENEWAL_LEAD = 90                   # a renewal window opens this many days before contract_end


def _acc_ref(p) -> dict:
    m = p.meta
    return {"id": p.id, "name": norm(m.get("name")) or p.id, "tier": norm(m.get("tier")), "stage": norm(m.get("stage")),
            "market": norm(m.get("market")).upper()}


def _day_item(kind: str, iid: str, day: dt.date, title: str, **extra) -> dict:
    return {"id": iid, "kind": kind, "status": extra.pop("status", ""), "title": title, "start": day.isoformat(),
            "end": day.isoformat(), "all_day": True, **extra}


def calendar_items(root: Path, reps: list[dict], accounts: list, touches: list[dict], on: dt.date) -> list[dict]:
    """Every dated item for the given reps (their accounts and appointments), plus their markets' holidays."""
    import lint
    from mama_common import LIVE_APPOINTMENT, load_appointments, market_cfg, market_holidays, read_page, to_date
    lo, hi = on - dt.timedelta(days=CAL_BEFORE), on + dt.timedelta(days=CAL_AFTER)
    inside = lambda d: d is not None and lo <= d <= hi
    rep_ids = {r["id"] for r in reps}
    by_id = {p.id: p for p in accounts}
    items: list[dict] = []

    for row in load_appointments(root).values():
        rep = norm(row.get("rep"))
        day = to_date(row.get("starts", "")[:10])
        if rep not in rep_ids or not inside(day):
            continue
        page = by_id.get(norm(row.get("account")))
        contact, cname = norm(row.get("contact")), ""
        if contact:
            cp = root / "wiki" / "contacts" / f"{contact}.md"
            cpage = read_page(cp, root) if cp.is_file() else None
            if cpage and cpage.meta:
                cname = norm(cpage.meta.get("name")) + (f" ({norm(cpage.meta.get('title'))})" if norm(cpage.meta.get("title")) else "")
        items.append({"id": row.get("id"), "kind": norm(row.get("kind")) or "meeting", "status": norm(row.get("status")),
                      "title": norm(row.get("title")), "start": row.get("starts"), "end": row.get("ends"), "all_day": False,
                      "tz": norm(row.get("tz")), "rep": rep, "account": _acc_ref(page) if page else {"id": norm(row.get("account"))},
                      "contact": contact, "contact_name": cname, "location": norm(row.get("location")),
                      "live": norm(row.get("status")) in LIVE_APPOINTMENT, "ref": "log/appointments.csv"})

    last = lint.last_touch_dates(touches)
    for p in accounts:
        m, rep = p.meta, norm(p.meta.get("owner"))
        if rep not in rep_ids or not is_active(m):
            continue
        ref, acc = f"wiki/accounts/{p.id}.md", _acc_ref(p)
        due = to_date(m.get("next_action_due"))
        if inside(due):
            items.append(_day_item("followup", f"fu-{p.id}", due, norm(m.get("next_action")) or norm(m.get("nba")) or "Next step",
                                   status="overdue" if due < on else "due", rep=rep, account=acc, nba=norm(m.get("nba")),
                                   reason=norm(m.get("nba_reason")), ref=ref))
        end = to_date(m.get("contract_end"))
        if end:
            if inside(end):
                items.append(_day_item("renewal", f"rn-{p.id}", end, f"Contract ends · {acc['name']}", rep=rep, account=acc, ref=ref))
            opens = end - dt.timedelta(days=RENEWAL_LEAD)
            if inside(opens):
                items.append(_day_item("renewal_window", f"rw-{p.id}", opens, f"Renewal window opens · {acc['name']}", rep=rep, account=acc, ref=ref))
        claimed = [d for d in (to_date(m.get("claimed_on")), to_date(m.get("allocated_on"))) if d]
        if claimed:
            touched = max(claimed + [d for d in (to_date(m.get("last_touch")), last.get(p.id)) if d])
            lapse = touched + dt.timedelta(days=lint.IDLE_DAYS)
            if inside(lapse):
                items.append(_day_item("claim_lapse", f"cl-{p.id}", lapse, f"Claim lapses · {acc['name']}",
                                       status="overdue" if lapse < on else "due", rep=rep, account=acc, ref=ref))

    markets = {str(mk).upper() for r in reps for mk in (r.get("markets") or [])}
    owned = {p.id for p in accounts if norm(p.meta.get("owner")) in rep_ids}
    for ev in iter_pages("event", root):
        m = ev.meta
        days = sorted(d for d in (to_date(x) for x in (m.get("dates") or [])) if d)
        matched = {norm(x) for x in (m.get("matched_accounts") or [])}
        if not days or not (norm(m.get("market")).upper() in markets or matched & owned):
            continue
        if not (inside(days[0]) or inside(days[-1])):
            continue
        items.append({"id": f"ev-{ev.id}", "kind": "event", "status": "", "title": norm(m.get("name")) or ev.id,
                      "start": days[0].isoformat(), "end": days[-1].isoformat(), "all_day": True, "market": norm(m.get("market")).upper(),
                      "location": norm(m.get("venue")), "matched": sorted(matched & owned), "ref": ev.rel})
    for mk in sorted(markets):
        for h in sorted(market_holidays(market_cfg(root, mk))):
            if inside(h):
                items.append(_day_item("holiday", f"ho-{mk}-{h}", h, f"{mk} public holiday", market=mk))
    items.sort(key=lambda x: (str(x["start"])[:10], not x.get("all_day"), str(x["start"]), x["kind"]))
    return items


def calendar_data(root: Path, reps: list[dict], accounts: list, touches: list[dict], on: dt.date, team: bool = False) -> dict:
    from mama_common import market_cfg, market_tz
    items = calendar_items(root, reps, accounts, touches, on)
    markets = sorted({str(mk).upper() for r in reps for mk in (r.get("markets") or [])})
    mcfg = {mk: {"tz": market_tz(root, mk)[0], "send_windows": market_cfg(root, mk).get("send_windows") or {}} for mk in markets}
    now = dt.datetime.combine(on, dt.datetime.now().time())
    upcoming = []
    for x in items:
        if x.get("all_day") or not x.get("live"):
            continue
        try:
            start = dt.datetime.fromisoformat(str(x["start"]))
        except ValueError:
            continue
        local_now = now.replace(tzinfo=start.tzinfo)
        if start >= local_now:
            upcoming.append((start, x))
    out = {"type": "team_calendar" if team else "calendar", "date": on.isoformat(), "generated": now_stamp(),
           "window": {"from": (on - dt.timedelta(days=CAL_BEFORE)).isoformat(), "to": (on + dt.timedelta(days=CAL_AFTER)).isoformat()},
           "tz": mcfg[markets[0]]["tz"] if markets else "Asia/Singapore", "markets": mcfg,
           "next_up": min(upcoming, key=lambda t: t[0])[1] if upcoming else None, "items": items}
    if team:
        load: dict[str, dict[str, int]] = {}
        for x in items:
            if x.get("rep") and (x.get("live") or x["kind"] == "followup"):
                day = str(x["start"])[:10]
                load.setdefault(x["rep"], {})[day] = load.setdefault(x["rep"], {}).get(day, 0) + 1
        out["reps"] = [{"rep": r["id"], "name": norm(r.get("name")), "markets": [str(m) for m in (r.get("markets") or [])],
                        "capacity": _int(r.get("max_active"))} for r in reps]
        out["by_rep_day"] = load
    return out


def build(root: Path | None = None, only: str | None = None) -> list[Path]:
    """Write the books; return the paths written."""
    root = root or repo_root()
    on = today()
    reps = load_reps(root)
    accounts = list(iter_pages("account", root))
    touches = load_touches(root)
    books = root / "wiki" / "books"
    books.mkdir(parents=True, exist_ok=True)
    stats: dict[str, dict] = {}
    written: list[Path] = []
    for rep in reps:
        mine = [p for p in accounts if norm(p.meta.get("owner")) == rep["id"]]
        stats[rep["id"]] = rep_stats(rep, mine, touches, on)
        if only and rep["id"] != only:
            continue
        path = books / f"{rep['id']}.md"
        write_text(path, render_rep(rep, stats[rep["id"]], on))
        _write_json(path.with_suffix(".json"), rep_data(rep, stats[rep["id"]], on))
        cal = books / f"{rep['id']}.calendar.json"
        _write_json(cal, calendar_data(root, [rep], accounts, touches, on))
        written += [path, path.with_suffix(".json"), cal]
    team = books / "team.md"
    write_text(team, render_team(reps, stats, accounts, root, on))
    _write_json(team.with_suffix(".json"), team_data(reps, stats, accounts, root, on))
    team_cal = books / "team.calendar.json"
    _write_json(team_cal, calendar_data(root, reps, accounts, touches, on, team=True))
    written += [team, team.with_suffix(".json"), team_cal]
    if not only:  # remove books of reps that no longer exist
        keep = {f"{r['id']}{ext}" for r in reps for ext in (".md", ".json", ".calendar.json")} | {"team.md", "team.json", "team.calendar.json"}
        for p in [*books.glob("*.md"), *books.glob("*.json")]:
            if p.name not in keep:
                try:
                    p.unlink()
                except OSError:
                    pass
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Rebuild wiki/books/<rep>.md/.json/.calendar.json and the team files.")
    ap.add_argument("--rep", help="rebuild only this rep's book (the team book is always rebuilt)")
    args = ap.parse_args(argv)
    setup_stdout()
    root = repo_root()
    for p in build(root, args.rep):
        print(f"Wrote {p.relative_to(root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
